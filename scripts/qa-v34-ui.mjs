import { chromium } from "playwright";
import fs from "node:fs";
const base = "http://127.0.0.1:8765/?v=v34-ig-completion";
const browser = await chromium.launch({ headless: true });
const findings = [], errors = [];
function check(value, message){findings.push({pass:!!value,message}); if(!value)throw Error("FAIL: "+message)}
async function click(page, selector){await page.locator(selector).first().click({timeout:10000})}
async function nav(page, route){await click(page, '.mp-header-nav nav [data-view="'+route+'"]');await page.locator('#mrRouteView[data-route="'+route+'"]').waitFor()}
async function run(){
 const source=JSON.parse(fs.readFileSync("data/instagram-electronics.json","utf8"));
 const context=await browser.newContext({viewport:{width:1440,height:900}});
 const page=await context.newPage();
 page.on("pageerror", e => errors.push(e.message));
 await page.goto(base, {waitUntil:"domcontentloaded"});
 await page.locator("#mrHomeDashboard .mr-card").first().waitFor({timeout:20000});
 check(await page.locator("#mrHomeDashboard .mr-card").count()>=4,"Homepage product cards load");
 const css=await page.locator('link[href*="v33.css"]').last().getAttribute("href");
 check(css?.includes("instagram-final"),"Latest Instagram styling loaded");
 await nav(page,"categories");
 check(await page.locator('#mrRouteView [data-sort-order] option').count()===3,"Category sort options");
 await page.locator('#mrRouteView [data-sort-order]').selectOption("등급순");
 check(await page.locator('#mrRouteView .mr-card').count()===5,"Category five-item pagination");
 const clipped=await page.locator('#mrRouteView .mr-card').evaluateAll(cards=>cards.some(card=>{const a=card.querySelector('.mr-card-actions');return a&&a.getBoundingClientRect().bottom>card.getBoundingClientRect().bottom+2}));
 check(!clipped,"Category action buttons not clipped");
 await click(page,'#mrRouteView .mr-card [data-detail]');
 await page.locator('#mrRouteView .mr-detail-page').waitFor();
 check(await page.locator('#mrRouteView [data-copyword]').count()===4,"Product detail four search keywords");
 await click(page,'#mrRouteView [data-detail-back]');
 check(await page.locator('#mrRouteView [data-sort-order]').inputValue()==="등급순","Detail back restores sort");
 await nav(page,"instagram");
 check(await page.locator('#mrRouteView .mr-instagram-gallery .mr-ig-tile').count()===5,"Domestic gallery five reels");
 check(await page.locator('#mrRouteView .mr-instagram-gallery .mr-ig-tile [data-prod]').count()===5,"Every reel has production control");
 check(await page.locator('#mrRouteView .mr-instagram-gallery .mr-ig-tile [data-fav]').count()===5,"Every reel has favorite control");
 await click(page,'#mrRouteView .mr-ig-tile .mr-ig-cover');
 await page.locator('.mr-ig-preview-overlay .mr-ig-preview-panel iframe').waitFor();
 check((await page.locator('.mr-ig-preview-panel iframe').getAttribute("src")).includes("/embed/captioned/"),"Clicking reel cover opens official Instagram embed");
 await click(page,'.mr-ig-preview-panel [data-preview-close]');
 check(await page.locator('.mr-ig-preview-overlay').count()===0,"Official preview closes cleanly");
 await page.locator('#mrIgSearch').fill("razer");
 await page.locator('#mrIgSearch').press("Enter");
 check(await page.locator('#mrRouteView .mr-ig-tile').count()>=1,"Instagram caption and account search");
 await click(page,'#mrRouteView [data-ig-search-clear]');
 check(await page.locator('#mrRouteView .mr-ig-tile').count()===5,"Instagram search reset");
 await page.locator('#mrRouteView [data-sort-order]').selectOption("조회순");
 check(await page.locator('#mrRouteView [data-sort-order]').inputValue()==="조회순","Instagram views sort");
 await click(page,'#mrRouteView .mr-ig-tile [data-ig-detail]');
 await page.locator('#mrRouteView .mr-ig-detail').waitFor();
 const src=await page.locator('#mrRouteView .mr-ig-embed iframe').getAttribute("src");
 check(!!src&&src.includes("instagram.com/"),"Detail uses official original post embed");
 check(await page.locator('#mrRouteView .mr-ig-detail-links a').count()===2,"Detail offers reel and account links");
 await click(page,'#mrRouteView .mr-ig-save-actions [data-fav]');
 check((await page.locator('#mrRouteView .mr-ig-save-actions [data-fav]').innerText()).includes("해제"),"Reel saved from detail");
 await click(page,'#mrRouteView .mr-ig-save-actions [data-prod]');
 check((await page.locator('#mrRouteView .mr-ig-save-actions [data-prod]').innerText()).includes("해제"),"Reel queued from detail");
 await page.screenshot({path:"qa-v34-ig-detail.png",fullPage:true});
 await click(page,'#mrRouteView [data-detail-back]');
 check(await page.locator('#mrRouteView [data-sort-order]').inputValue()==="조회순","Reel detail back restores sort");
 await nav(page,"favorites");
 check(await page.locator('#mrRouteView .mr-ig-tile').count()===1,"Saved reel appears in favorites");
 await nav(page,"production");
 check(await page.locator('#mrRouteView .v33-production-row').count()===1,"Saved reel appears in production");
 const overlap=await page.locator('#mrRouteView .v33-row-product').first().evaluate(row=>{const photo=row.querySelector('img').getBoundingClientRect(),title=row.querySelector('span').getBoundingClientRect();return photo.right>title.left+1});
 check(!overlap,"Production thumbnail and title do not overlap");
 await page.locator('#mrRouteView [data-state]').first().selectOption("촬영중");
 check(await page.locator('#mrRouteView [data-state]').first().inputValue()==="촬영중","Production stage selector works");
 await page.screenshot({path:"qa-v34-ig-production.png",fullPage:true});
 await click(page,'#mrRouteView .v33-production-row [data-production-remove]');
 check(await page.locator('#mrRouteView .v33-production-row').count()===0,"Production delete removes test reel");
 await nav(page,"favorites");
 await click(page,'#mrRouteView .mr-ig-tile [data-fav]');
 check(await page.locator('#mrRouteView .mr-ig-tile').count()===0,"Favorite removal cleans test reel");
 await nav(page,"instagram");
 await click(page,'#mrRouteView [data-filter="해외상품"]');
 check(await page.locator('#mrRouteView .mr-ig-tile').count()===5,"Overseas first page has five");
 check(await page.locator('#mrRouteView .mr-pager button').count()===4,"Overseas gallery has four pages");
 await page.locator('#mrRouteView [data-sort-order]').selectOption("좋아요순");
 check(await page.locator('#mrRouteView [data-sort-order]').inputValue()==="좋아요순","Instagram likes sort");
 await click(page,'#mrRouteView .mr-pager [data-page="4"]');
 check(await page.locator('#mrRouteView .mr-ig-tile').count()===5,"Overseas fourth page five reels");
 await page.screenshot({path:"qa-v34-instagram-grid.png",fullPage:true});
 await click(page,'#mrCommandButton');
 await page.locator("#mrCommandInput").waitFor();
 await page.locator("#mrCommandInput").fill("1-1");
 await click(page,'#mrCommandForm button');
 check(await page.locator('#mrCommandResults .mr-ig-tile').count()===source.domestic.length,"Domestic command output matches source");
 await page.locator("#mrCommandInput").fill("1-2");
 await click(page,'#mrCommandForm button');
 check(await page.locator('#mrCommandResults .mr-ig-tile').count()===source.overseas.length,"Overseas command output matches source");
 await click(page,'#mrCommandView .mr-command-grid [data-command="2"]');
 await page.locator('#mrCommandView .mr-command-detail').waitFor();
 await page.locator('#mrCommandView input[name="mr-script-format"][value="리뷰형"]').check();
 check((await page.locator('#mrCommandView .mr-generated').innerText()).includes("선택한 형식: 리뷰형"),"Script format controls update output");
 const mobile=await browser.newPage({viewport:{width:375,height:812},isMobile:true});
 await mobile.goto(base+"#mp=route%3Ainstagram",{waitUntil:"domcontentloaded"});
 await mobile.locator('#mrRouteView .mr-ig-tile').first().waitFor();
 check(await mobile.locator('#mrRouteView .mr-ig-tile').count()===5,"Mobile Instagram loads 5 reels");
 const dims=await mobile.locator('#mrRouteView .mr-instagram-gallery').evaluate(el=>({width:el.getBoundingClientRect().width,children:[...el.children].slice(0,2).map(x=>x.getBoundingClientRect().width)}));
 check(dims.children.length===2&&dims.children[0]<dims.width*.7,"Mobile gallery uses two columns");
 await click(mobile,'#mrRouteView .mr-ig-tile [data-ig-detail]');
 check(await mobile.locator('#mrRouteView .mr-ig-detail').isVisible(),"Mobile reel detail opens");
 await page.close();await mobile.close();
}
try{await run();}catch(e){errors.push(e.stack||String(e));process.exitCode=1;}finally{
 console.log(JSON.stringify({findings,errors},null,2));
 await browser.close();
}
